import { existsSync, readFileSync, writeFileSync, mkdirSync, chmodSync, chownSync, copyFileSync, cpSync, readdirSync, lstatSync, renameSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { isIP } from 'node:net';
import { createHash, randomBytes } from 'node:crypto';
import { fileURLToPath } from 'node:url';

export function deploymentAddress(input) {
  const url = new URL(input.includes('://') ? input : `https://${input}`);
  if (url.protocol !== 'https:' || url.username || url.password || url.pathname !== '/' || url.search || url.hash || url.port) {
    throw new Error('Use a bare HTTPS domain or fixed IP on port 443, without credentials or a path');
  }
  const host = url.hostname.replace(/^\[|\]$/g, '');
  const local = Boolean(isIP(host)) || host === 'localhost' || !host.includes('.') || /\.(local|lan|home|internal|test)$/.test(host);
  return { origin: url.origin, site: url.host, local };
}

export function caddyfile({ site, local }) {
  return `# Generated by hrt init. No caller-supplied forwarding headers are trusted.
${site} {
  ${local ? 'tls internal' : ''}
  encode zstd gzip
  header {
    X-Content-Type-Options nosniff
    Referrer-Policy no-referrer
    Strict-Transport-Security "max-age=31536000"
    Content-Security-Policy "default-src 'self'; script-src 'self' 'wasm-unsafe-eval'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; font-src 'self' data:; connect-src 'self'; frame-src 'none'; worker-src 'self' blob:; media-src 'self' blob:; frame-ancestors 'none'; base-uri 'self'; object-src 'none'; form-action 'self'"
    -Server
  }
  @api path /health /stats /auth /auth/* /api /api/* /mcp /mcp/* /supporters /supporters/* /webhooks /webhooks/*
  handle @api {
    reverse_proxy api:8788 {
      header_up -CF-Connecting-IP
      header_up -Forwarded
      header_up X-Forwarded-For {remote_host}
      header_up X-Forwarded-Proto https
    }
  }
  @fresh path / /index.html /sw.js /workbox-* /manifest.webmanifest
  header @fresh Cache-Control "no-cache"
  handle {
    root * /srv
    try_files {path} {path}/index.html /index.html
    file_server
  }
}
# Internal container health check, never published by Compose.
http://:8080 {
  handle /health {
    reverse_proxy api:8788
  }
}
`;
}

function privateWrite(path, data, mode = 0o600) {
  writeFileSync(path, data, { flag: 'wx', mode });
  chmodSync(path, mode);
  hostOwner(path);
}
function hostOwner(path) {
  if (process.getuid?.() === 0 && /^\d+$/.test(process.env.HOST_UID ?? '') && /^\d+$/.test(process.env.HOST_GID ?? '')) {
    chownSync(path, Number(process.env.HOST_UID), Number(process.env.HOST_GID));
  }
}
function keyPermissions(path) {
  // The API image runs as node (uid/gid 1000). No key is baked into an image.
  if (process.platform !== 'win32' && process.getuid?.() === 0) chownSync(path, 1000, 1000);
  chmodSync(path, 0o400);
}
export function initialize(root, input) {
  const address = deploymentAddress(input);
  if (existsSync(join(root, '.env')) || existsSync(join(root, 'secrets')) || existsSync(join(root, 'Caddyfile'))) throw new Error('Already initialized or partial initialization exists; refusing to overwrite');
  const version = readFileSync(join(root, 'VERSION'), 'utf8').trim();
  requireVersion(version);
  mkdirSync(join(root, 'secrets'), { mode: 0o700 });
  hostOwner(join(root, 'secrets'));
  privateWrite(join(root, 'secrets/master.key'), randomBytes(32));
  keyPermissions(join(root, 'secrets/master.key'));
  privateWrite(join(root, 'Caddyfile'), caddyfile(address), 0o644);
  privateWrite(join(root, '.env'), `COMPOSE_PROJECT_NAME=kira-hrt-${randomBytes(5).toString('hex')}\nHRT_VERSION=${version}\nPUBLIC_ORIGIN=${address.origin}\nPOSTGRES_PASSWORD=${randomBytes(32).toString('hex')}\n`);
  console.log(`Initialized ${address.origin}; HTTPS: ${address.local ? 'local CA (install root certificate on each device)' : 'public certificate (DNS and ports 80/443 required)'}`);
}
function requireVersion(value) {
  if (!/^\d+\.\d+\.\d+(?:-[a-zA-Z0-9.-]+)?$/.test(value)) throw new Error('Use an explicit release version such as 2.2.0; latest is not accepted');
}
function backupPath(root, name) {
  if (!/^[a-zA-Z0-9][a-zA-Z0-9_-]{0,90}$/.test(name ?? '')) throw new Error('Invalid backup name');
  return join(root, 'backups', name);
}
function files(root, prefix = '') {
  return readdirSync(join(root, prefix)).flatMap(name => {
    const rel = prefix ? `${prefix}/${name}` : name;
    const stat = lstatSync(join(root, rel));
    if (stat.isSymbolicLink()) throw new Error('Symlinks are not allowed in backups');
    return stat.isDirectory() ? files(root, rel) : [rel];
  });
}
const digest = path => createHash('sha256').update(readFileSync(path)).digest('hex');
function protectBackupTree(path) {
  const stat = lstatSync(path);
  if (stat.isSymbolicLink()) throw new Error('Symlinks are not allowed in backups');
  if (stat.isDirectory()) for (const child of readdirSync(path)) protectBackupTree(join(path, child));
  chmodSync(path, stat.isDirectory() ? 0o700 : 0o600);
  hostOwner(path);
}
export function prepareBackup(root, name, ca = '/caddy') {
  const dir = backupPath(root, name);
  mkdirSync(join(root, 'backups'), { recursive: true, mode: 0o700 });
  mkdirSync(dir, { mode: 0o700 });
  hostOwner(join(root, 'backups'));
  hostOwner(dir);
  for (const [source, target] of [['.env', 'config.env'], ['Caddyfile', 'Caddyfile'], ['secrets/master.key', 'master.key']]) {
    copyFileSync(join(root, source), join(dir, target));
    chmodSync(join(dir, target), 0o600);
    hostOwner(join(dir, target));
  }
  if (existsSync(ca)) cpSync(ca, join(dir, 'caddy'), { recursive: true, dereference: false });
  protectBackupTree(dir);
}
export function finishBackup(root, name) {
  const dir = backupPath(root, name);
  if (readFileSync(join(dir, 'database.dump')).subarray(0, 5).toString() !== 'PGDMP') throw new Error('Missing PostgreSQL custom-format dump');
  const checksums = Object.fromEntries(files(dir).map(file => [file, digest(join(dir, file))]));
  protectBackupTree(dir);
  privateWrite(join(dir, 'manifest.json'), JSON.stringify({ format: 1, checksums }, null, 2));
  console.log(`Backup complete: backups/${name}. Contains the master key, credentials and CA private keys; store securely.`);
}
export function verifyBackup(root, name) {
  const dir = backupPath(root, name);
  const manifest = JSON.parse(readFileSync(join(dir, 'manifest.json'), 'utf8'));
  if (manifest.format !== 1 || !manifest.checksums || typeof manifest.checksums !== 'object') throw new Error('Unsupported backup');
  const found = files(dir).filter(file => file !== 'manifest.json').sort();
  if (JSON.stringify(found) !== JSON.stringify(Object.keys(manifest.checksums).sort())) throw new Error('Backup file list mismatch');
  for (const [file, expected] of Object.entries(manifest.checksums)) {
    if (digest(join(dir, file)) !== expected) throw new Error(`Backup checksum mismatch: ${file}`);
  }
  for (const required of ['database.dump', 'config.env', 'master.key', 'Caddyfile']) {
    if (!found.includes(required)) throw new Error(`Backup missing ${required}`);
  }
  if (readFileSync(join(dir, 'master.key')).length !== 32) throw new Error('Invalid backup master key');
  return dir;
}
export function restoreFiles(root, name, ca = '/caddy') {
  const dir = verifyBackup(root, name);
  if (existsSync(join(root, '.env')) || existsSync(join(root, 'secrets')) || existsSync(join(root, 'Caddyfile'))) throw new Error('Restore requires an uninitialized directory');
  if (existsSync(ca) && readdirSync(ca).length) throw new Error('Restore requires an empty certificate volume');
  mkdirSync(join(root, 'secrets'), { mode: 0o700 });
  hostOwner(join(root, 'secrets'));
  privateWrite(join(root, 'secrets/master.key'), readFileSync(join(dir, 'master.key')));
  keyPermissions(join(root, 'secrets/master.key'));
  privateWrite(join(root, 'Caddyfile'), readFileSync(join(dir, 'Caddyfile')), 0o644);
  const config = readFileSync(join(dir, 'config.env'), 'utf8').replace(/^COMPOSE_PROJECT_NAME=.*$/m, `COMPOSE_PROJECT_NAME=kira-hrt-${randomBytes(5).toString('hex')}`);
  privateWrite(join(root, '.env'), config);
  // Certificates are restored separately, after Compose loads the new project name.
}
export function setVersion(root, version) {
  requireVersion(version);
  const path = join(root, '.env');
  const config = readFileSync(path, 'utf8');
  if (!/^HRT_VERSION=.+$/m.test(config)) throw new Error('Missing HRT_VERSION');
  const temporary = join(root, `.env.version-${randomBytes(6).toString('hex')}`);
  privateWrite(temporary, config.replace(/^HRT_VERSION=.+$/m, `HRT_VERSION=${version}`));
  renameSync(temporary, path);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const [command, value] = process.argv.slice(2);
    const root = process.cwd();
    if (command === 'init') initialize(root, value ?? '');
    else if (command === 'backup-prepare') prepareBackup(root, value);
    else if (command === 'backup-finish') finishBackup(root, value);
    else if (command === 'backup-verify') verifyBackup(root, value);
    else if (command === 'restore-files') restoreFiles(root, value);
    else if (command === 'restore-ca') {
      const dir = verifyBackup(root, value);
      if (readdirSync('/caddy').length) throw new Error('Certificate volume is not empty');
      if (existsSync(join(dir, 'caddy'))) cpSync(join(dir, 'caddy'), '/caddy', { recursive: true });
    } else if (command === 'version') setVersion(root, value);
    else if (command === 'validate-version') requireVersion(value);
    else if (command === 'cert') {
      const source = '/caddy/caddy/pki/authorities/local/root.crt';
      copyFileSync(source, join(root, 'local-root.crt'));
      chmodSync(join(root, 'local-root.crt'), 0o644);
      console.log('Exported local-root.crt (public certificate only)');
    } else throw new Error('Unknown management command');
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
